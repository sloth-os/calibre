#!/usr/bin/env node
/*
 * Worker integration test: drive the REAL worker.js against the REAL wasm
 * bundle the way a browser would — via the same message protocol the app
 * uses. Node stands in for the browser: worker.js runs as an ESM module
 * worker (the same kind app.js spawns in a browser) with its import()/fetch
 * contract satisfied by shims below (see worker.js's "Node-testable by
 * contract" note).
 *
 * Usage: node tests/worker-integration.test.mjs [bundle-dir]
 *   bundle-dir defaults to /tmp/bundle-out (patches/build-bundle.sh output).
 *   It may also be a STAGED SITE directory (site-publish): the test detects
 *   the deployed layout (wasm/pyodide/ nested, wasm/calibre-bundle.zip) and
 *   boots against it with no rewriting, so CI validates the exact geometry
 *   GitHub Pages will serve.
 *
 * Verifies: bundle content gates (src/qt excluded, shims/qt present), boot
 * with the qt resolution canary, formats listing, TXT->EPUB conversion with
 * a valid EPUB result (zip + mimetype), TXT->MOBI with a generated cover
 * (BOOKMOBI magic, no cover failures in the log), cover-fixture EPUB->AZW3
 * + metadata read, and the error path (garbage input).
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import vm from 'node:vm';
import { Worker } from 'node:worker_threads';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..');
const BUNDLE_DIR = process.argv[2] ? path.resolve(process.argv[2]) : '/tmp/bundle-out';

let pass = 0, fail = 0;
let teardownDone = false;
const failures = [];
function check(name, cond, extra) {
  if (cond) { pass++; console.log('PASS  ' + name); }
  else { fail++; failures.push(name); console.log('FAIL  ' + name + (extra ? ' -- ' + extra : '')); }
}

// Node >= 23 backs Buffers with shared 64 KB slabs: `.buffer` is the WHOLE
// slab (byteLength 65536, possibly carrying other allocations' leftovers),
// not just this string's bytes — and worker.js reads the whole backing store
// (new Uint8Array(msg.input)). Sending `.buffer` fed the engine tens of KB of
// NULs/garbage and made this suite flaky (~1 in 3: "embedded null byte" /
// "All strings must be XML compatible"). Slice exactly, like the browser's
// file.arrayBuffer() and TextEncoder do.
function exactUtf8(str) {
  const b = Buffer.from(str, 'utf8');
  return b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength);
}

// Two accepted layouts:
//   bundle:    BUNDLE_DIR/calibre-bundle.zip + BUNDLE_DIR/pyodide/  (build output)
//   staged site: BUNDLE_DIR/wasm/calibre-bundle.zip + BUNDLE_DIR/wasm/pyodide/
// Marker = the entry the runtime actually loads (pyodide.mjs — the module
// worker's import target). Keying on a file nothing loads (e.g. the unused
// pyodide.js UMD build) would silently SKIP this suite the moment that file
// is cleaned up from the bundle.
const SITE_LAYOUT =
  fs.existsSync(path.join(BUNDLE_DIR, 'wasm', 'calibre-bundle.zip')) &&
  fs.existsSync(path.join(BUNDLE_DIR, 'wasm', 'pyodide', 'pyodide.mjs'));
if (!SITE_LAYOUT && !fs.existsSync(path.join(BUNDLE_DIR, 'calibre-bundle.zip'))) {
  const missing = `no engine at ${BUNDLE_DIR} (need wasm/calibre-bundle.zip + wasm/pyodide/pyodide.mjs, or calibre-bundle.zip at the root)`;
  // An explicitly passed dir (CI) without an engine is a HARD failure: a
  // silent SKIP there is exactly the green-but-unverified hole this suite
  // exists to close. The default dir (local dev) may legitimately be absent.
  if (process.argv[2]) {
    console.error('FAIL: ' + missing);
    process.exit(1);
  }
  console.log(`SKIPPED (${missing}; run patches/build-bundle.sh first)`);
  process.exit(0);
}

// ------------------------------------------------- bundle content gates ---
// The production bug this suite must never regress: calibre's AUTOGENERATED
// src/qt/ (a lazy PyQt6 loader stub with no real symbols) shipped inside the
// bundle and shadowed the Pillow-backed shims/qt/ — worker.js puts src/
// first on sys.path, so every cover path died with "ImportError: cannot
// import name 'QBuffer' from 'qt.core' (/site/src/qt/core.py)". The bundle
// build excludes src/qt/ (patches/build-bundle.sh); these checks read the
// zip's central directory directly, so a packaging regression fails HERE —
// before any boot, in whichever layout CI hands us.
const BUNDLE_ZIP = SITE_LAYOUT
  ? path.join(BUNDLE_DIR, 'wasm', 'calibre-bundle.zip')
  : path.join(BUNDLE_DIR, 'calibre-bundle.zip');

function zipEntryNames(zipPath) {
  const buf = fs.readFileSync(zipPath);
  let eocd = -1; // End of Central Directory: scan backwards for the signature
  for (let i = buf.length - 22; i >= 0 && i > buf.length - 22 - 65536; i--) {
    if (buf.readUInt32LE(i) === 0x06054b50) { eocd = i; break; }
  }
  if (eocd < 0) throw new Error('EOCD not found in ' + zipPath);
  const count = buf.readUInt16LE(eocd + 10);
  let off = buf.readUInt32LE(eocd + 16);
  if (count === 0xffff || off === 0xffffffff) {
    throw new Error('zip64 central directory — extend zipEntryNames');
  }
  const names = [];
  for (let i = 0; i < count; i++) {
    if (buf.readUInt32LE(off) !== 0x02014b50) throw new Error('bad CD signature at ' + off);
    const nameLen = buf.readUInt16LE(off + 28);
    const extraLen = buf.readUInt16LE(off + 30);
    const commentLen = buf.readUInt16LE(off + 32);
    names.push(buf.toString('utf8', off + 46, off + 46 + nameLen));
    off += 46 + nameLen + extraLen + commentLen;
  }
  return names;
}

const entries = zipEntryNames(BUNDLE_ZIP);
check('bundle: src/qt excluded (would shadow shims/qt — the QBuffer ImportError)',
  !entries.some(n => n === 'src/qt' || n.startsWith('src/qt/')),
  entries.filter(n => n.startsWith('src/qt/')).slice(0, 5).join(', '));
check('bundle: shims/qt/core.py present', entries.includes('shims/qt/core.py'));
check('bundle: src/calibre intact (rsync exclude not over-broad)',
  entries.includes('src/calibre/__init__.py'));

// ---------------------------------------------------------------- worker shim
// worker.js is a MODULE worker script: it uses self.postMessage /
// self.onmessage / dynamic import() / fetch. Node's worker_threads has none
// of the browser globals, so the worker file is prefixed with a preamble
// that polyfills them (fetch reads from disk; import() of pyodide.mjs works
// natively via file:// URLs) — worker.js itself runs unmodified.
const workerSrc = fs.readFileSync(path.join(REPO, 'worker.js'), 'utf8');
const appSrc = fs.readFileSync(path.join(REPO, 'app.js'), 'utf8');

// Pyodide's "Classic web workers are not supported" guard only fires in
// BROWSERS (its env detection sees Node first), so the harness cannot trip
// that wire itself — assert the contract statically instead.
check('worker.js never calls importScripts (pyodide rejects classic workers)',
  !/\bimportScripts\s*\(/.test(workerSrc));
check("worker.js imports the ESM pyodide entry",
  /PYODIDE_MJS_URL = '\.\/wasm\/pyodide\/pyodide\.mjs'/.test(workerSrc));
check("app.js spawns worker.js with { type: 'module' }",
  /new Worker\('\.\/worker\.js',\s*\{\s*type:\s*'module'\s*\}\)/.test(appSrc));

console.log(`booting worker with ${SITE_LAYOUT ? 'staged site' : 'bundle'} layout at`, BUNDLE_DIR);

// The worker resolves ./wasm/pyodide/... relative to its own location. In a
// staged site that path is real; for a raw bundle dir a wasm -> . symlink
// mirrors the deployed layout so every URL resolves without touching
// worker.js. (symlinkSync EEXIST is fine — a real wasm/ dir wins.)
try {
  fs.symlinkSync('.', path.join(BUNDLE_DIR, 'wasm'), 'dir');
} catch (e) {
  if (e.code !== 'EEXIST') throw e;
}
// The preamble runs INSIDE the module worker before worker.js: defines the
// browser globals worker.js expects (self/location/postMessage/onmessage/
// fetch) plus a loadPyodide assignment interceptor — importScripts is
// deliberately NOT shimmed: module workers do not have it, and pyodide
// rejects any browser environment where it does work.
const PREAMBLE = `
import fs from 'node:fs';
import path from 'node:path';
import { parentPort } from 'node:worker_threads';
const BUNDLE_DIR = ${JSON.stringify(BUNDLE_DIR)};

// Browser worker contract on top of worker_threads:
// self.postMessage -> parentPort.postMessage, self.onmessage -> parentPort
// (a MessagePort keeps the worker alive until terminated, matching a
// browser worker's lifecycle).
globalThis.self = globalThis;
globalThis.location = { href: 'file://' + BUNDLE_DIR + '/' };
globalThis.postMessage = (m) => parentPort.postMessage(m);
Object.defineProperty(globalThis, 'onmessage', {
  configurable: true,
  set(fn) { parentPort.on('message', (d) => fn({ data: d })); },
  get() { return undefined; },
});

// worker.js dynamic-import()s pyodide.mjs through an absolute file:// URL
// derived from location.href (native ESM import — no shim needed), then
// assigns globalThis.loadPyodide. Intercept the ASSIGNMENT: pyodide under
// Node resolves indexURL with path.resolve, which mangles file:// URLs, so
// rewrite the file:// indexURL worker.js derives into a plain path.
let __loadPyodide = null;
Object.defineProperty(globalThis, 'loadPyodide', {
  configurable: true,
  set(fn) {
    __loadPyodide = (opts) => {
      if (opts && typeof opts.indexURL === 'string' && opts.indexURL.startsWith('file://')) {
        opts = { ...opts, indexURL: opts.indexURL.slice('file://'.length) };
      }
      return fn(opts);
    };
  },
  get() { return __loadPyodide; },
});
globalThis.fetch = async (url) => {
  const s = String(url);
  let p = s.startsWith('file://') ? s.slice('file://'.length) : s;
  if (!path.isAbsolute(p)) p = path.join(BUNDLE_DIR, p.replace(/^\\//, ''));
  if (!fs.existsSync(p)) {
    // worker paths carry a wasm/ prefix that maps to the bundle root.
    const alt = path.join(BUNDLE_DIR, p.replace(/^.*?wasm\\//, ''));
    if (fs.existsSync(alt)) p = alt;
  }
  const data = fs.readFileSync(p);
  return {
    ok: true,
    status: 200,
    arrayBuffer: async () => data.buffer.slice(data.byteOffset, data.byteOffset + data.byteLength),
    json: async () => JSON.parse(data.toString('utf8')),
  };
};
`;

fs.mkdirSync(path.join(os.tmpdir(), 'calibre-web-tests'), { recursive: true });
// .mjs so Node unambiguously treats the concatenated preamble+worker as ESM,
// exactly like a browser module worker.
// pid-suffixed: concurrent runs of this suite must not overwrite each
// other's boot file (a shared name lets one process boot another's harness).
const workerFile = path.join(os.tmpdir(), 'calibre-web-tests', `worker-boot-${process.pid}.mjs`);
fs.writeFileSync(workerFile, PREAMBLE + '\n' + workerSrc);

const w = new Worker(workerFile, { type: 'module', stdout: true, stderr: true });

let nextId = 1;
const pending = new Map();
function send(type, payload) {
  return new Promise((resolve, reject) => {
    const id = nextId++;
    pending.set(id, { resolve, reject });
    w.postMessage({ id, type, ...payload });
  });
}

const bootLines = [];
w.on('message', (msg) => {
  if (msg.type === 'boot-progress' || msg.type === 'progress') {
    if (msg.line) bootLines.push(msg.line);
    if (msg.stage) console.log('  [boot]', msg.stage, `(${msg.pct}%)`);
 return;
  }
  const waiter = pending.get(msg.id);
  if (!waiter) return;
  pending.delete(msg.id);
  if (msg.type === 'error') {
    const err = new Error(msg.message);
    err.engineLog = msg.log; // calibre traceback lines, when the worker has them
    waiter.reject(err);
  } else waiter.resolve(msg);
});
w.on('error', (e) => { console.error('worker error:', e); process.exitCode = 1; });
w.on('exit', (c) => {
  // A nonzero exit during teardown (after the checks printed) is a teardown
  // artifact, not a test failure — the assertions above already decided.
  if (c !== 0 && !teardownDone) console.error('worker exited', c);
});

// ------------------------------------------------------------------- tests --
try {
  console.log('waiting for boot...');
  const ready = await send('init', {});
  check('worker boots to ready', true);
  console.log('boot log tail:', bootLines.slice(-3).join(' | '));

  // Boot canary: worker.js imports qt.core eagerly and logs the resolved
  // path — it MUST be the shim. A packaging regression that the zip gates
  // above somehow missed (e.g. a stray qt stub outside src/qt) fails here
  // with the actual resolved location in the failure message.
  check('boot canary: qt.core resolves to the shim',
    bootLines.some(l => /qt\.core: \/site\/shims\/qt\/core\.py/.test(l)),
    bootLines.filter(l => l.includes('qt.core')).join(' | ') || '(no qt.core line in boot log)');

  const fmts = await send('formats', {});
  check('formats: input list non-empty', Array.isArray(fmts.input) && fmts.input.length > 5,
    `got ${fmts.input && fmts.input.length}`);
  check('formats: output list non-empty', Array.isArray(fmts.output) && fmts.output.length > 5,
    `got ${fmts.output && fmts.output.length}`);
  check('formats: epub + mobi + azw3 available',
 ['epub', 'mobi', 'azw3'].every(f => fmts.output.includes(f)),
    String(fmts.output));
  check('formats: pdf NOT offered (unsupported in wasm)', !fmts.output.includes('pdf'));
  check('formats: version reported', typeof fmts.version === 'string' && fmts.version.length > 0, fmts.version);

  // TXT -> EPUB
  const txt = ('Chapter One\n\nThe quick brown fox jumps over the lazy dog. '.repeat(100) +
 '\n\nChapter Two\n\nIt was the best of times. '.repeat(100));
  const conv = await send('convert', {
 name: 'test.txt',
    input: exactUtf8(txt),
    outputFormat: 'epub',
  });
  check('convert TXT->EPUB returns a result', conv.type === 'convert-result', JSON.stringify(conv).slice(0, 100));
  check('convert: output name .epub', /\.epub$/.test(conv.name || ''), conv.name);
  check('convert: bytes non-trivial', conv.size > 1000, `size ${conv.size}`);

  // Validate the EPUB: zip magic + mimetype entry
  const bytes = Buffer.from(conv.data);
  check('epub: zip magic', bytes[0] === 0x50 && bytes[1] === 0x4b, bytes.subarray(0, 2).toString('hex'));
  const zipEnd = bytes.indexOf(Buffer.from('mimetypeapplication/epub+zip'));
  check('epub: mimetype entry present', zipEnd > 0);

  // TXT -> MOBI exercises the GENERATED-cover path: no cover in the input,
  // so calibre draws a default cover (QFont/QPainter -> QImage -> QBuffer,
  // covers.py) and a MOBI thumbnail (rescale_image). Under the shadowed qt
  // stub this conversion still "succeeded" — the failure was swallowed into
  // log.exception('Failed to generate default cover') /
  // log.warn('Failed to generate thumbnail') — so the log scan below is the
  // actual regression signal, not the exit status.
  const mobi = await send('convert', {
    name: 'test.txt',
    input: exactUtf8(txt),
    outputFormat: 'mobi',
  });
  check('convert TXT->MOBI returns a result', mobi.type === 'convert-result',
    JSON.stringify(mobi).slice(0, 100));
  const mbytes = Buffer.from(mobi.data);
  check('mobi: PalmDB BOOKMOBI magic at offset 60',
    mbytes.subarray(60, 68).toString('ascii') === 'BOOKMOBI',
    mbytes.subarray(60, 68).toString('hex'));
  check('mobi: size > 10000 (cover + content, not an empty shell)',
    mobi.size > 10000, `size ${mobi.size}`);

  // Cover-bearing EPUB -> AZW3: the user-reported failure was a HARD
  // ImportError mid-conversion on exactly this path (the input carries a
  // real JPEG cover; the KF8 writer rescales it through img.py/imageops and
  // serializes via QBuffer). Fixture: tests/fixtures/cover-book.epub,
  // regenerated by tests/fixtures/make-cover-book.py.
  const fixturePath = path.join(REPO, 'tests', 'fixtures', 'cover-book.epub');
  const fbuf = fs.readFileSync(fixturePath);
  const fixture = fbuf.buffer.slice(fbuf.byteOffset, fbuf.byteOffset + fbuf.byteLength);

  const md = await send('metadata', { name: 'cover-book.epub', input: fixture });
  check('metadata: fixture title read back',
    md.metadata && md.metadata.title === 'Cover Test Book', JSON.stringify(md.metadata));
  check('metadata: fixture author read back',
    md.metadata && (md.metadata.authors || []).includes('Sloth QA'),
    JSON.stringify(md.metadata && md.metadata.authors));

  const azw3 = await send('convert', {
    name: 'cover-book.epub',
    input: fixture,
    outputFormat: 'azw3',
  });
  check('convert cover EPUB->AZW3 returns a result', azw3.type === 'convert-result',
    JSON.stringify(azw3).slice(0, 120));
  const abytes = Buffer.from(azw3.data);
  check('azw3: PalmDB BOOKMOBI magic at offset 60',
    abytes.subarray(60, 68).toString('ascii') === 'BOOKMOBI',
    abytes.subarray(60, 68).toString('hex'));
  check('azw3: size plausible (cover survives the trip)', azw3.size > 20000,
    `size ${azw3.size}`);

  // Cover-failure log scan across BOTH cover conversions above. calibre's
  // Log writes to stdout, which the worker forwards as progress lines —
  // bootLines accumulates every python-side line since boot.
  const coverFailures = bootLines.filter(l => /Failed to generate (default cover|thumbnail)/.test(l));
  check('no cover-generation failures logged (qt shim live in-engine)',
    coverFailures.length === 0, coverFailures.slice(0, 3).join(' | '));

  // ---- output profiles (the chooser feature) -------------------------------
  // profiles come from calibre's plugin registry via list_formats() — never
  // hardcoded in JS. 'default' must be first (registry order) so the UI can
  // preselect it.
  check('formats: profiles reported (engine registry, not hardcoded)',
    Array.isArray(fmts.profiles) && fmts.profiles.length > 30,
    `got ${fmts.profiles && fmts.profiles.length}`);
  const pDefault = (fmts.profiles || [])[0];
  check('formats: first profile is "default"',
    Boolean(pDefault && pDefault.short_name === 'default'),
    JSON.stringify(pDefault));
  const pKindle = (fmts.profiles || []).find(p => p.short_name === 'kindle');
  check('formats: kindle profile present with name/description/screen',
    Boolean(pKindle && pKindle.name === 'Kindle' &&
      typeof pKindle.description === 'string' && pKindle.description.length > 0 &&
      Array.isArray(pKindle.screen) && pKindle.screen.length === 2),
    JSON.stringify(pKindle));
  // Screen entries must be NUMBERS with calibre's real values (profiles.py:
  // KindleOutput.screen_size = (525, 640)) — the UI's 'W × H px' /
  // 'unlimited' formatting logic depends on numeric comparisons, and
  // Array.isArray + length 2 alone would pass string entries too. The
  // tablet profile carries the (10000, 10000) unlimited sentinel
  // (profiles.py TabletOutput), which drives the width>=10000 rule.
  const pTablet = (fmts.profiles || []).find(p => p.short_name === 'tablet');
  check('formats: screen sizes are real numbers (kindle 525x640, tablet 10000 sentinel)',
    Boolean(pKindle && pKindle.screen.every(Number.isFinite) &&
      pKindle.screen[0] === 525 && pKindle.screen[1] === 640) &&
    Boolean(pTablet && pTablet.screen[0] >= 10000),
    JSON.stringify({ kindle: pKindle && pKindle.screen, tablet: pTablet && pTablet.screen }));
  check('formats: every profile has short_name + name strings',
    (fmts.profiles || []).every(p => typeof p.short_name === 'string' && p.short_name &&
      typeof p.name === 'string' && p.name),
    (fmts.profiles || []).filter(p => !p.short_name || !p.name).map(p => JSON.stringify(p)).join(' | '));

  // The convert-result echoes the RESOLVED profile short_name read back from
  // plumber.opts.output_profile AFTER run() — proof the option injection
  // (merge_ui_recommendations, the CLI mechanism) actually took effect, not
  // just that the request was accepted. An invalid name makes calibre fall
  // back to 'default' with a warning.
  const profMobi = await send('convert', {
    name: 'test.txt',
    input: exactUtf8(txt),
    outputFormat: 'mobi',
    options: { output_profile: 'kindle' },
  });
  check('convert with options.output_profile=kindle returns a result',
    profMobi.type === 'convert-result', JSON.stringify(profMobi).slice(0, 120));
  check('convert-result echoes resolved profile kindle',
    profMobi.profile === 'kindle', String(profMobi.profile));
  const profBytes = Buffer.from(profMobi.data);
  check('profile MOBI: BOOKMOBI magic intact',
    profBytes.subarray(60, 68).toString('ascii') === 'BOOKMOBI',
    profBytes.subarray(60, 68).toString('hex'));

  // No cross-conversion leakage: options are merged into per-Plumber-instance
  // OptionRecommendation clones, so the NEXT conversion without options must
  // resolve 'default', not inherit 'kindle' from the long-lived process.
  const noProf = await send('convert', {
    name: 'test.txt',
    input: exactUtf8(txt),
    outputFormat: 'epub',
  });
  check('conversion without options resolves the default profile (no leak)',
    noProf.type === 'convert-result' && noProf.profile === 'default',
    `type ${noProf.type}, profile ${noProf.profile}`);

  // Invalid profile name: calibre's set_profile() warns and falls back —
  // the conversion still succeeds and the echo shows 'default'.
  const badProf = await send('convert', {
    name: 'test.txt',
    input: exactUtf8(txt),
    outputFormat: 'epub',
    options: { output_profile: 'no-such-device' },
  });
  check('invalid profile falls back to default (engine survives)',
    badProf.type === 'convert-result' && badProf.profile === 'default',
    `type ${badProf.type}, profile ${badProf.profile}`);
  // The FileStream sink added in convert_file(): calibre's set_profile()
  // warn must travel back IN the result's log array — not only on stdout.
  // Proves convert-result.log is no longer the always-empty dead field.
  check('invalid profile: calibre warning captured in result log array',
    Array.isArray(badProf.log) && badProf.log.some(l => /no longer available/i.test(l)),
    'log=' + JSON.stringify(Array.isArray(badProf.log) ? badProf.log.slice(0, 4) : badProf.log).slice(0, 200));

  // Options with values that would break naive JS->Python literal embedding
  // (booleans, null, quotes, unicode) must survive the double-JSON encoding.
  const weirdOpts = await send('convert', {
    name: 'test.txt',
    input: exactUtf8(txt),
    outputFormat: 'epub',
    options: {
      output_profile: 'tablet',
      no_chapters_in_toc: true,
      title: "Bob's «Book» — ünïcode",
      comments: null,
    },
  });
  check('options with bool/null/quote/unicode values convert cleanly',
    weirdOpts.type === 'convert-result' && weirdOpts.profile === 'tablet',
    JSON.stringify({ t: weirdOpts.type, p: weirdOpts.profile, e: weirdOpts.error }).slice(0, 160));
  // ...and PROVE the non-profile option values actually took effect. The
  // check above alone passes a mutant whose merge keeps only output_profile
  // (verified experimentally): title/comments would be silently discarded
  // with nothing observing them. Pipe the produced EPUB back through the
  // metadata path: the title option must have overridden the input-derived
  // one ("Bob's «Book» — ünïcode" — quotes, guillemets, em dash, diacritics
  // surviving the double-JSON encoding AND calibre's OPF writer).
  if (weirdOpts.type === 'convert-result' && weirdOpts.data) {
    const mdBack = await send('metadata', { name: weirdOpts.name, input: weirdOpts.data });
    check('option values take effect: title override survives roundtrip',
      mdBack.metadata && mdBack.metadata.title === "Bob's «Book» — ünïcode",
      JSON.stringify(mdBack.metadata).slice(0, 200));
    check('option values take effect: null comments handled (no crash, empty/absent)',
      mdBack.metadata && (mdBack.metadata.comments === '' || mdBack.metadata.comments == null),
      JSON.stringify(mdBack.metadata && mdBack.metadata.comments).slice(0, 120));
  } else {
    check('option values take effect: title override survives roundtrip', false,
      'conversion did not return data: ' + weirdOpts.type);
    check('option values take effect: null comments handled (no crash, empty/absent)', false,
      'conversion did not return data: ' + weirdOpts.type);
  }

  // Garbage input -> clean engine-level error (or a tolerated conversion),
  // never a hang or a worker crash. send() rejects precisely on the worker's
  // {type:'error'} message; a hang would surface as the run-level timeout
  // instead, so any resolution/rejection here is a clean outcome.
  const bad = await send('convert', {
    name: 'bad.epub',
    input: exactUtf8('this is not an ebook at all, just some text'),
    outputFormat: 'azw3',
  }).then(m => ({ ok: true, m }), e => ({ ok: false, e }));
  check('garbage input: rejected or errored cleanly',
    bad.ok ? bad.m.type === 'convert-result'
 : bad.e instanceof Error && bad.e.message.length > 0,
 bad.ok ? 'converted anyway (tolerated): ' + JSON.stringify(bad.m).slice(0, 80)
 : 'clean error: ' + String(bad.e && bad.e.message).slice(0, 120));

  console.log(`\n${pass} passed, ${fail} failed`);
  if (fail) { failures.forEach(f => console.log('FAILED: ' + f)); process.exitCode = 1; }
} catch (e) {
  console.error('TEST CRASH:', e);
  if (e && Array.isArray(e.engineLog) && e.engineLog.length) {
    console.error('--- engine log tail ---');
    e.engineLog.slice(-25).forEach((l) => console.error('  ' + l));
  }
  process.exitCode = 1;
} finally {
  teardownDone = true;
  await w.terminate();
}
